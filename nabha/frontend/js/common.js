async function api(u, m, b) {
  try {
    const r = await fetch(u, {
      method: m || "GET",
      headers: {
        "Content-Type": "application/json",
        Authorization: S.token ? "Bearer " + S.token : "",
      },
      body: b ? JSON.stringify(b) : undefined,
    });
    if (r.status === 401) {
      if (!u.includes("/login")) {
        logout();
        return { error: "unauthorized" };
      }
    }
    return await r.json();
  } catch (e) {
    console.warn("API offline fallback for:", u, e.message);
    return null;
  }
}

