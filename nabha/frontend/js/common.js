// Progress Sync Helpers
function act(ty, id, sc) {
  if (!S.p) S.p = { l: [], q: {} };
  if (!Array.isArray(S.p.l)) S.p.l = [];
  if (!S.p.q) S.p.q = {};

  const numId = Number(id) || id;
  if (ty === "l") {
    if (!S.p.l.some((x) => String(x) === String(numId))) {
      S.p.l.push(numId);
    }
  } else if (ty === "q") {
    S.p.q[String(numId)] = Math.max(0, Math.min(100, Number(sc != null ? sc : 0)));
    if (!S.p.l.some((x) => String(x) === String(numId))) {
      S.p.l.push(numId);
    }
  }
  if (S.user && S.user.id) {
    localStorage["p_" + S.user.id] = JSON.stringify(S.p);
  }
  const actObj = { t: ty, type: ty, id: numId, score: sc, u: (S.user && S.user.id), at: Date.now() };
  const q = JSON.parse(localStorage.nabha_progress_queue || "[]");
  q.push(actObj);
  localStorage.nabha_progress_queue = JSON.stringify(q);
  flush();
}

async function flush() {
  if (!S.token || !S.user) return;
  const q = JSON.parse(localStorage.nabha_progress_queue || "[]");
  if (!q.length) return;
  try {
    const res = await api("/api/sync", "POST", { ops: q });
    if (res && (res.ok || res.progress)) {
      localStorage.nabha_progress_queue = "[]";
      if (res.progress) {
        const sL = res.progress.l || [];
        const sQ = res.progress.q || {};
        for (const lid of sL) {
          if (!S.p.l.some((x) => String(x) === String(lid))) {
            S.p.l.push(lid);
          }
        }
        S.p.q = Object.assign({}, sQ, S.p.q || {});
        if (S.user && S.user.id) {
          localStorage["p_" + S.user.id] = JSON.stringify(S.p);
        }
      }
    }
  } catch (e) {
    console.warn("Progress sync offline fallback");
  }
}

async function doSync() {
  if (!S.token) {
    showToast(t("login"));
    return;
  }
  await flush();
  const res = await api("/api/progress");
  if (res) {
    const p = res.progress || (res.l ? res : null);
    if (p) {
      const sL = p.l || [];
      const sQ = p.q || {};
      for (const lid of sL) {
        if (!S.p.l.some((x) => String(x) === String(lid))) {
          S.p.l.push(lid);
        }
      }
      S.p.q = Object.assign({}, sQ, S.p.q || {});
      if (S.user && S.user.id) {
        localStorage["p_" + S.user.id] = JSON.stringify(S.p);
      }
    }
  }
  showToast(t("synced"));
  if (typeof render === "function") render();
}
